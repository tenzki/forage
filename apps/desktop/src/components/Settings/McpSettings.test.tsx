vi.mock('@tauri-apps/api/core', () => ({ invoke: vi.fn() }))
const initialMcp = useMcpStore.getState()
const initialSettings = useSettingsStore.getState()
const tool = { id: `mcp_l_${'a'.repeat(48)}`, remoteName: 'lookup', name: 'Lookup', description: 'Find a record', fingerprint: 'a'.repeat(64), inputSchema: { type: 'object' } }
const connection: McpConnection = { id: 'mine', name: 'Mine', environment: 'local', enabled: true, tools: [tool] }
const candidate = { id: 'd'.repeat(64), name: 'Pen', sources: ['Codex'], transport: 'stdio' as const, inputs: [] }
function NavigatedMcp() {
  const navigation = useSettingsRouter()
  return <SettingsNavigationProvider value={navigation}><div className="settings-content"><button data-settings-section="mcp" onClick={() => navigation.select('mcp')}>MCP section</button><button onClick={() => navigation.select('general')}>General section</button><output>{navigation.route.section} / {navigation.route.page ?? 'overview'}</output><McpSettings /></div></SettingsNavigationProvider>
}
beforeEach(() => {
  vi.mocked(invoke).mockReset()
  vi.mocked(invoke).mockResolvedValue('local')
  vi.mocked(publishLocalAgentConfiguration).mockReset()
  vi.mocked(publishLocalAgentConfiguration).mockResolvedValue('local_only')
  useMcpStore.setState({ ...initialMcp, loaded: true, connections: [], serverConnections: [], busy: false, error: null,
    discovery: { candidates: [], warnings: [] }, scanConnections: vi.fn(async () => undefined),
  })
  useSettingsStore.setState({ ...initialSettings, isLoaded: true, enabledToolIds: [], agents: [{ id: 'designer', name: 'Designer', description: '', systemPrompt: 'Design.', toolIds: [] }], grantMcpToolAccess: vi.fn(async () => undefined), setToolEnabled: vi.fn(async () => undefined) })
})
afterEach(() => { cleanup(); useMcpStore.setState(initialMcp); useSettingsStore.setState(initialSettings) })

describe('MCP settings', () => {
  it.each(['Add server', 'Manage'])('uses the design back link above the standalone %s heading', async (action) => {
    const user = userEvent.setup()
    useMcpStore.setState({ connections: [connection] })
    render(<McpSettings />)
    await user.click(await screen.findByRole('button', { name: action }))
    const back = screen.getByRole('button', { name: 'Back to MCP servers' })
    expect(back.textContent).toBe('←MCP servers')
    expect(back.parentElement!.firstElementChild).toBe(back)
    await user.click(back)
    expect(screen.getByRole('heading', { name: 'MCP servers' })).toBeTruthy()
  })

  it('separates connected and detected inventories using definition identity rather than name', async () => {
    useMcpStore.setState({ connections: [{ ...connection, name: 'Pen', discoveryId: candidate.id }], discovery: { candidates: [candidate, { ...candidate, id: 'c'.repeat(64), sources: ['Cursor'] }, { ...candidate, id: 'b'.repeat(64), sources: ['Cursor'] }], warnings: ['Claude Desktop: could not read its MCP configuration.'] } })
    render(<McpSettings />)
    expect(await screen.findByRole('heading', { name: 'Connected · 1' })).toBeTruthy()
    expect(screen.getByRole('heading', { name: 'Detected on this computer · 2' })).toBeTruthy()
    expect(screen.getAllByRole('group', { name: 'Found Pen' })).toHaveLength(2)
    expect(screen.getByText('Definition cccccccc')).toBeTruthy()
    expect(screen.getByText('Definition bbbbbbbb')).toBeTruthy()
    expect(screen.getByText(/Discovery is incomplete/)).toBeTruthy()
    expect(screen.getByText(/Added from Codex/)).toBeTruthy()
    expect(screen.queryByLabelText('Server URL')).toBeNull()
    expect(screen.getByRole('button', { name: 'Add server' })).toBeTruthy()
    expect(document.querySelectorAll('svg.lucide-plug').length).toBe(3)
    expect(document.querySelector('img')).toBeNull()
  })

  it('discovers without connecting and explicitly reviews individual tools and agents after import', async () => {
    const imported = { ...connection, discoveryId: candidate.id, name: 'Pen' }
    const connect = vi.fn(async () => { useMcpStore.setState({ connections: [imported] }); return imported })
    const scan = vi.fn(async () => { useMcpStore.setState({ discovery: { candidates: [candidate], warnings: [] } }) })
    useMcpStore.setState({ scanConnections: scan, connectCandidate: connect })
    render(<McpSettings />)
    const found = await screen.findByRole('group', { name: 'Found Pen' })
    expect(scan).toHaveBeenCalledTimes(1)
    expect(connect).not.toHaveBeenCalled()
    expect(useSettingsStore.getState().grantMcpToolAccess).not.toHaveBeenCalled()
    fireEvent.click(within(found).getByRole('button', { name: 'Connect' }))
    const access = await screen.findByRole('group', { name: 'Tool access for Pen' })
    expect(connect).toHaveBeenCalledWith(candidate.id, {}, 'Pen')
    expect((within(access).getByRole('checkbox', { name: 'Enable Lookup' }) as HTMLInputElement).checked).toBe(false)
    fireEvent.click(within(access).getByRole('checkbox', { name: 'Enable Lookup' }))
    fireEvent.click(within(access).getByRole('checkbox', { name: 'Designer' }))
    fireEvent.click(within(access).getByRole('button', { name: 'Save access' }))
    await waitFor(() => expect(useSettingsStore.getState().grantMcpToolAccess).toHaveBeenCalledWith([tool.id], ['designer'], [tool.id]))
    expect(await screen.findByRole('heading', { name: 'Detected on this computer · 0' })).toBeTruthy()
  })

  it('requests missing credentials and keeps changed-source failures actionable without error secrets', async () => {
    const missing = { ...candidate, name: 'Search', transport: 'http' as const, sources: ['VS Code'], inputs: [{ key: 'header:Authorization', label: 'Authorization header' }] }
    const imported = { ...connection, discoveryId: candidate.id, name: 'Search', tools: [] }
    const connect = vi.fn().mockRejectedValueOnce(new Error('This connection changed. Scan again. private-value')).mockImplementationOnce(async () => { useMcpStore.setState({ connections: [imported] }); return imported })
    useMcpStore.setState({ discovery: { candidates: [missing], warnings: [] }, connectCandidate: connect })
    render(<McpSettings />)
    const found = await screen.findByRole('group', { name: 'Found Search' })
    expect((within(found).getByText('Connect') as HTMLButtonElement).disabled).toBe(true)
    fireEvent.change(within(found).getByLabelText('Authorization header'), { target: { value: 'Bearer private-value' } })
    fireEvent.click(within(found).getByText('Connect'))
    expect((await screen.findByRole('alert')).textContent).toContain('Scan again')
    expect(screen.getByRole('alert').textContent).not.toContain('private-value')
    fireEvent.click(within(found).getByText('Connect'))
    await waitFor(() => expect(connect).toHaveBeenLastCalledWith(candidate.id, { 'header:Authorization': 'Bearer private-value' }, 'Search'))
    await waitFor(() => expect(screen.queryByLabelText('Authorization header')).toBeNull())
    expect(await screen.findByText('This server provides no agent tools.')).toBeTruthy()
  })

  it('shows unsupported candidates without a Connect action and offers manual setup', async () => {
    useMcpStore.setState({ discovery: { candidates: [{ ...candidate, issue: 'This connection uses app-specific settings. Use advanced setup.' }], warnings: [] } })
    render(<McpSettings />)
    const found = await screen.findByRole('group', { name: 'Found Pen' })
    expect(within(found).queryByRole('button', { name: 'Connect' })).toBeNull()
    expect(within(found).getByText(/Use Add server/)).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Add server' })).toBeTruthy()
  })

  it('retains connections during empty or failed discovery and scanning grants nothing', async () => {
    const scan = vi.fn(async () => { useMcpStore.setState({ discoveryError: 'scanner secret-token failed' }) })
    useMcpStore.setState({ connections: [connection], scanConnections: scan })
    render(<McpSettings />)
    expect(await screen.findByRole('group', { name: 'Connected Mine' })).toBeTruthy()
    expect(await screen.findByRole('alert')).toHaveProperty('textContent', 'Could not scan device configurations. Existing connections remain available; try Scan again or Add server.')
    expect(screen.getByText(/No unconnected servers detected/)).toBeTruthy()
    fireEvent.click(screen.getByText('Scan again'))
    expect(scan).toHaveBeenCalledTimes(2)
    expect(useSettingsStore.getState().grantMcpToolAccess).not.toHaveBeenCalled()
  })

  it('routes Add server to URL-first setup and returns focus after cancel', async () => {
    render(<NavigatedMcp />)
    const add = await screen.findByRole('button', { name: 'Add server' })
    add.focus(); fireEvent.click(add)
    expect(screen.getByText('mcp / setup')).toBeTruthy()
    expect(screen.getByLabelText('Server URL')).toBeTruthy()
    expect(screen.queryByText('Detected on this computer · 0')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))
    await waitFor(() => expect(document.activeElement).toBe(screen.getByRole('button', { name: 'Add server' })))
    expect(screen.queryByLabelText('Server URL')).toBeNull()
    expect(useSettingsStore.getState().grantMcpToolAccess).not.toHaveBeenCalled()
  })

  it('protects dirty setup on cancel and section changes without connecting', async () => {
    const connect = vi.fn(async () => connection)
    useMcpStore.setState({ addConnection: connect })
    render(<NavigatedMcp />)
    fireEvent.click(await screen.findByRole('button', { name: 'Add server' }))
    fireEvent.change(screen.getByLabelText('Server name'), { target: { value: 'Draft' } })
    fireEvent.click(screen.getByRole('button', { name: 'Manual credentials' }))
    fireEvent.change(screen.getByLabelText('Access token (optional)'), { target: { value: 'secret' } })
    fireEvent.click(screen.getByRole('button', { name: 'General section' }))
    expect(screen.getByRole('alertdialog')).toBeTruthy()
    fireEvent.click(screen.getByText('Keep editing'))
    expect((screen.getByLabelText('Server name') as HTMLInputElement).value).toBe('Draft')
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))
    fireEvent.click(screen.getByText('Discard changes'))
    expect(screen.queryByLabelText('Access token (optional)')).toBeNull()
    expect(connect).not.toHaveBeenCalled()
  })

  it('connects manual URL setup directly to review with no automatic grants', async () => {
    const connect = vi.fn(async () => { useMcpStore.setState({ connections: [connection] }); return connection })
    useMcpStore.setState({ addConnection: connect })
    render(<McpSettings />)
    fireEvent.click(await screen.findByRole('button', { name: 'Add server' }))
    fireEvent.change(screen.getByLabelText('Server name'), { target: { value: 'Mine' } })
    fireEvent.change(screen.getByLabelText('Server URL'), { target: { value: 'https://search.example/mcp' } })
    fireEvent.click(screen.getByRole('button', { name: 'Manual credentials' }))
    fireEvent.change(screen.getByLabelText('Access token (optional)'), { target: { value: 'private-token' } })
    fireEvent.click(screen.getByText('Connect server'))
    expect(await screen.findByRole('group', { name: 'Tool access for Mine' })).toBeTruthy()
    expect(connect).toHaveBeenCalledWith('Mine', { url: 'https://search.example/mcp', headers: { Authorization: 'Bearer private-token' }, authentication: { method: 'manual' } })
    expect(screen.queryByLabelText('Access token (optional)')).toBeNull()
    expect(useSettingsStore.getState().grantMcpToolAccess).not.toHaveBeenCalled()
  })
  it('opens review after multi-server JSON import and cancel leaves all imports without grants', async () => {
    const second = { ...connection, id: 'second', name: 'Second' }
    const entries = [connection, second]
    const importConnections = vi.fn(async () => { useMcpStore.setState({ connections: entries }); return entries })
    useMcpStore.setState({ importConnections })
    render(<McpSettings />)
    fireEvent.click(await screen.findByRole('button', { name: 'Add server' }))
    fireEvent.change(screen.getByLabelText('Server configuration'), { target: { value: '{"mcpServers":{"mine":{"command":"node"},"second":{"command":"node"}}}' } })
    fireEvent.click(screen.getByText('Import and connect'))
    expect(await screen.findByRole('group', { name: 'Tool access for Mine' })).toBeTruthy()
    expect(screen.getByText(/1 more imported connections to review/)).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))
    expect(await screen.findByRole('heading', { name: 'Connected · 2' })).toBeTruthy()
    expect(useSettingsStore.getState().grantMcpToolAccess).not.toHaveBeenCalled()
    expect(useMcpStore.getState().connections).toEqual(entries)
  })

  it('loads backend inventory without local mutations and retries without desktop fallback', async () => {
    vi.mocked(invoke).mockResolvedValue('server')
    const loadServer = vi.fn(async () => { throw new Error('Backend disconnected private-key') })
    useMcpStore.setState({ connections: [connection], loadServer })
    render(<McpSettings />)
    expect((await screen.findByRole('alert')).textContent).toContain('Could not load MCP servers')
    expect(screen.getByRole('alert').textContent).not.toContain('private-key')
    expect(screen.queryByText('Mine')).toBeNull()
    expect(screen.queryByRole('button', { name: 'Add server' })).toBeNull()
    expect(screen.queryByRole('button', { name: 'Scan again' })).toBeNull()
    expect(useMcpStore.getState().scanConnections).not.toHaveBeenCalled()
    fireEvent.click(screen.getByText('Try again'))
    await waitFor(() => expect(loadServer).toHaveBeenCalledTimes(2))
  })

  it('offers retry instead of assuming local mode when persisted mode cannot be read', async () => {
    vi.mocked(invoke).mockRejectedValueOnce(new Error('Could not read mode secret-path'))
    render(<McpSettings />)
    expect((await screen.findByRole('alert')).textContent).toContain('saved execution mode')
    expect(screen.queryByRole('button', { name: 'Add server' })).toBeNull()
    fireEvent.click(screen.getByText('Try again'))
    expect(await screen.findByRole('button', { name: 'Add server' })).toBeTruthy()
  })

  it('shows only server tools and retains authorized permission editing and agent selection', async () => {
    vi.mocked(invoke).mockResolvedValue('server')
    const server = { ...connection, id: 'backend', name: 'Shared search', environment: 'server' as const, tools: [{ ...tool, id: `mcp_s_${'b'.repeat(48)}` }] }
    const loadServer = vi.fn(async () => { useMcpStore.setState({ serverConnections: [server] }) })
    useMcpStore.setState({ connections: [connection], loadServer })
    const view = render(<McpSettings />)
    const row = await screen.findByRole('group', { name: 'Connected Shared search' })
    fireEvent.click(within(row).getByText('Manage'))
    expect(screen.getByRole('checkbox', { name: 'Enable Lookup' })).toBeTruthy()
    expect(screen.queryByText('Mine')).toBeNull()
    expect(screen.queryByRole('button', { name: 'Disconnect' })).toBeNull()
    expect(screen.queryByRole('button', { name: 'Disable connection' })).toBeNull()
    fireEvent.click(screen.getByRole('checkbox', { name: 'Enable Lookup' }))
    fireEvent.click(screen.getByRole('checkbox', { name: 'Designer' }))
    fireEvent.click(screen.getByText('Save access'))
    await waitFor(() => expect(useSettingsStore.getState().grantMcpToolAccess).toHaveBeenCalledWith([server.tools[0]!.id], ['designer'], [server.tools[0]!.id]))
    view.unmount()
    render(<AgentSettings reportError={vi.fn()} />)
    await waitFor(() => expect(loadServer).toHaveBeenCalledTimes(2))
    fireEvent.click(screen.getByText('Add agent'))
    expect(await screen.findByRole('checkbox', { name: 'Shared search' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Choose tools for Shared search' }))
    expect(screen.getByRole('checkbox', { name: 'Lookup' })).toBeTruthy()
    expect(screen.queryByRole('checkbox', { name: 'Mine' })).toBeNull()
  })

  it('allows inspection and refresh of disabled or empty connected servers', async () => {
    useMcpStore.setState({ connections: [{ ...connection, enabled: false, tools: [] }] })
    render(<McpSettings />)
    fireEvent.click(within(await screen.findByRole('group', { name: 'Connected Mine' })).getByText('Manage'))
    expect(screen.getByText('This server provides no agent tools.')).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Refresh tools' })).toBeTruthy()
    expect((screen.getByRole('button', { name: 'Save access' }) as HTMLButtonElement).disabled).toBe(true)
  })
  it('keeps server tool selections mounted and usable during definition updates', async () => {
    vi.mocked(invoke).mockResolvedValue('server')
    const server = { ...connection, environment: 'server' as const, tools: [{ ...tool, id: `mcp_s_${'b'.repeat(48)}` }] }
    const changed = { ...server, tools: [{ ...server.tools[0]!, fingerprint: 'c'.repeat(64) }] }
    const loadServer = vi.fn().mockImplementationOnce(async () => { useMcpStore.setState({ serverConnections: [server] }) }).mockImplementationOnce(async () => { useMcpStore.setState({ serverConnections: [changed] }) })
    useMcpStore.setState({ loadServer })
    render(<McpSettings />)
    fireEvent.click(within(await screen.findByRole('group', { name: 'Connected Mine' })).getByText('Manage'))
    fireEvent.click(screen.getByRole('checkbox', { name: 'Enable Lookup' }))
    fireEvent.click(screen.getByText('Refresh tools'))
    await waitFor(() => expect(loadServer).toHaveBeenCalledTimes(2))
    expect(screen.queryByText(/tool inventory changed/)).toBeNull()
    expect((screen.getByRole('checkbox', { name: 'Enable Lookup' }) as HTMLInputElement).checked).toBe(true)
    expect((screen.getByRole('button', { name: 'Save access' }) as HTMLButtonElement).disabled).toBe(false)
    expect(useSettingsStore.getState().grantMcpToolAccess).not.toHaveBeenCalled()
    expect(useMcpStore.getState().scanConnections).not.toHaveBeenCalled()
  })
  it('returns to Manage focus after cancelling review and falls back when a connection disappears', async () => {
    useMcpStore.setState({ connections: [connection] })
    render(<NavigatedMcp />)
    const manage = within(await screen.findByRole('group', { name: 'Connected Mine' })).getByText('Manage')
    manage.focus(); fireEvent.click(manage)
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))
    await waitFor(() => expect(document.activeElement).toBe(screen.getByRole('button', { name: 'Manage' })))
    fireEvent.click(screen.getByRole('button', { name: 'Manage' }))
    act(() => useMcpStore.setState({ connections: [] }))
    expect(await screen.findByText(/connection is no longer available/)).toBeTruthy()
    expect(screen.getByText('mcp / overview')).toBeTruthy()
    expect(screen.queryByRole('group', { name: 'Tool access for Mine' })).toBeNull()
  })
})

