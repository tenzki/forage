import { describe, expect, it } from 'vitest'
import { canClosePane, initialWorkspace, outlineTarget, workspaceReducer as reduce, type PaneLocation } from './workspaceState'
const outline = (nodeId: string | null): PaneLocation => ({ kind: 'outline', nodeId })
const web: PaneLocation = { kind: 'web', href: 'https://example.test', sourceNodeId: 'source' }

describe('session-local workspace state', () => {
  it('inserts immediately after the source without removing its right-hand trail or deduplicating targets', () => {
    let state = initialWorkspace('a')
    state = reduce(state, { type: 'open', sourceId: 'a', id: 'b', location: outline('same') })
    state = reduce(state, { type: 'open', sourceId: 'a', id: 'c', location: outline('same') })
    expect(state.panes.map(pane => pane.id)).toEqual(['a', 'c', 'b'])
    expect(state.activePaneId).toBe('c')
    expect(reduce(state, { type: 'open', sourceId: 'missing', id: 'd', location: web })).toBe(state)
    expect(reduce(state, { type: 'open', sourceId: 'a', id: 'b', location: web })).toBe(state)
  })
  it('splits a location with matching scroll/width and fresh history', () => {
    let state = reduce(initialWorkspace('a'), { type: 'navigate', id: 'a', location: outline('branch') })
    state = reduce(state, { type: 'scroll', id: 'a', scrollTop: 287 })
    state = reduce(state, { type: 'width', id: 'a', width: 610 })
    state = reduce(state, { type: 'split', sourceId: 'a', id: 'b' })
    expect(state.panes[1]).toMatchObject({ id: 'b', width: 610, current: { location: outline('branch'), scrollTop: 287 }, back: [], forward: [] })
    expect(state.panes[0].back).toHaveLength(1)
  })
  it('restores independent visit scroll positions and clears forward only on new navigation', () => {
    let state = reduce(initialWorkspace('a'), { type: 'split', sourceId: 'a', id: 'b' })
    state = reduce(state, { type: 'scroll', id: 'a', scrollTop: 190 })
    state = reduce(state, { type: 'navigate', id: 'a', location: outline('branch') })
    state = reduce(state, { type: 'scroll', id: 'a', scrollTop: 75 })
    state = reduce(state, { type: 'back', id: 'a' })
    expect(state.panes[0].current).toEqual({ location: outline(null), scrollTop: 190 })
    expect(state.panes[1].current.scrollTop).toBe(0)
    state = reduce(state, { type: 'forward', id: 'a' })
    expect(state.panes[0].current.scrollTop).toBe(75)
    state = reduce(state, { type: 'back', id: 'a' })
    state = reduce(state, { type: 'navigate', id: 'a', location: outline('other') })
    expect(state.panes[0].forward).toEqual([])
  })
  it('retains an outline even with web panes, and targets the last surviving active outline', () => {
    let state = reduce(initialWorkspace('a'), { type: 'open', sourceId: 'a', id: 'web', location: web })
    expect(canClosePane(state, 'a')).toBe(false)
    expect(reduce(state, { type: 'close', id: 'a' })).toBe(state)
    expect(outlineTarget(state).id).toBe('a')
    state = reduce(state, { type: 'open', sourceId: 'web', id: 'b', location: outline('branch') })
    state = reduce(state, { type: 'activate', id: 'web' })
    expect(outlineTarget(state).id).toBe('b')
    state = reduce(state, { type: 'close', id: 'b' })
    expect(state.activePaneId).toBe('web')
    expect(outlineTarget(state).id).toBe('a')
  })
  it('closing active panes chooses left then right; inactive closure preserves focus', () => {
    let state = reduce(initialWorkspace('a'), { type: 'open', sourceId: 'a', id: 'b', location: outline('branch') })
    state = reduce(state, { type: 'open', sourceId: 'b', id: 'c', location: web })
    state = reduce(state, { type: 'close', id: 'a' })
    expect(state.activePaneId).toBe('c')
    state = reduce(state, { type: 'close', id: 'c' })
    expect(state.activePaneId).toBe('b')
    state = reduce(state, { type: 'open', sourceId: 'b', id: 'd', location: outline(null) })
    state = reduce(state, { type: 'activate', id: 'b' })
    state = reduce(state, { type: 'close', id: 'b' })
    expect(state.activePaneId).toBe('d')
  })
  it('keeps web provenance through browsing and does not convert outline panes to web panes', () => {
    let state = reduce(initialWorkspace('a'), { type: 'open', sourceId: 'a', id: 'w', location: web })
    const before = state
    expect(reduce(state, { type: 'navigate', id: 'a', location: web })).toBe(before)
    state = reduce(state, { type: 'navigate', id: 'w', location: { ...web, kind: 'web', href: 'https://example.test/next' } })
    state = reduce(state, { type: 'back', id: 'w' })
    expect(state.panes[1].current.location).toEqual(web)
  })
})
